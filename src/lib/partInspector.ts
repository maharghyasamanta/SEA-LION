import {
  ATMOSPHERIC_PRESSURE_KPA,
  DamCrack,
  LASER_SPACING_MM,
  PilotInputVector,
  ROV_BOUNDS,
  RovState,
  SeverityLevel,
  SeverityThresholds,
  classifySeverity,
  computeAcousticScore,
  computeDepthFromPressureKpa,
  computePressureKpaFromDepth,
  computeScaleMmPerPx,
  computeSimulatedDotDistancePx,
  computeThrusterPwm,
} from './crackAnalysis';

export type InspectablePartId =
  | 'camera'
  | 'lasers'
  | 'piezo'
  | 'pressure'
  | 'thrusters'
  | 'tether'
  | 'shore-unit'
  | 'crack-C-01'
  | 'crack-C-02'
  | 'crack-C-03'
  | 'crack-C-04';

export type PartStatus = 'Idle' | 'Active' | 'Alert';

export interface PartReadingRow {
  label: string;
  value: string;
}

export interface PartInspectionDetails {
  id: InspectablePartId;
  name: string;
  summary: string;
  status: PartStatus;
  awsService: string;
  readings: PartReadingRow[];
  severity?: SeverityLevel;
  note?: string;
}

export interface BuildPartContext {
  rov: RovState;
  cracks: readonly DamCrack[];
  thresholds: SeverityThresholds;
  pilotVector: PilotInputVector;
  isMoving: boolean;
  straddledCrack: DamCrack | null;
}

export function buildPartInspectionDetails(
  partId: InspectablePartId,
  ctx: BuildPartContext,
): PartInspectionDetails {
  const { rov, cracks, thresholds, pilotVector, isMoving, straddledCrack } = ctx;
  const standoffM = Math.max(0.05, ROV_BOUNDS.wallFaceXM - rov.xM);
  const dotDistancePx = computeSimulatedDotDistancePx(rov.xM);
  const scaleMmPerPx = computeScaleMmPerPx(dotDistancePx);
  const dotsVisible = standoffM <= 0.65;
  const acoustic = computeAcousticScore(rov, cracks);
  const pressureKpa = computePressureKpaFromDepth(rov.depthM, ATMOSPHERIC_PRESSURE_KPA);
  const computedDepthM = computeDepthFromPressureKpa(pressureKpa, ATMOSPHERIC_PRESSURE_KPA);
  const pwm = computeThrusterPwm(pilotVector, isMoving);

  if (partId === 'camera') {
    return {
      id: partId,
      name: 'Underwater Camera & View-Cone',
      summary:
        'Captures concrete surface imagery and twin 50 mm laser dots for optical crack width screening.',
      status: dotsVisible ? 'Active' : 'Idle',
      awsService: 'Amazon S3 (raw frame) → AWS Lambda (OpenCV)',
      readings: [
        { label: 'Resolution', value: '1920 × 1080 px' },
        { label: 'Focus Range', value: '0.10 – 0.65 m' },
        { label: 'Wall Standoff (SIM)', value: `${standoffM.toFixed(2)} m` },
        { label: 'Laser Dots Visible', value: dotsVisible ? 'Yes' : 'No (Move closer)' },
      ],
    };
  }

  if (partId === 'lasers') {
    return {
      id: partId,
      name: 'Twin 50 mm Calibration Lasers',
      summary:
        'Projects two parallel laser dots 50 mm apart onto the dam wall to calibrate pixel-to-millimeter scale.',
      status: straddledCrack ? 'Active' : dotsVisible ? 'Active' : 'Idle',
      awsService: 'AWS Lambda (OpenCV dot separation calibration)',
      readings: [
        { label: 'Physical Spacing', value: `${LASER_SPACING_MM} mm` },
        { label: 'Dot Distance (SIM)', value: `${dotDistancePx} px` },
        { label: 'Scale (50 / px)', value: `${scaleMmPerPx.toFixed(3)} mm/px` },
        { label: 'Target Lock', value: straddledCrack ? straddledCrack.id : 'Scanning wall' },
      ],
    };
  }

  if (partId === 'piezo') {
    const status: PartStatus =
      acoustic.status === 'Active Leak Detected'
        ? 'Alert'
        : acoustic.status === 'Elevated Hiss'
          ? 'Active'
          : 'Idle';
    return {
      id: partId,
      name: 'Piezo Hydrophone Sensor',
      summary:
        'Detects high-frequency acoustic hiss generated by pressurized water seeping through wall cracks.',
      status,
      awsService: 'AWS IoT Core → Amazon DynamoDB',
      readings: [
        { label: 'Acoustic Score (SIM)', value: `${acoustic.score} / 100` },
        { label: 'Signal State', value: acoustic.status },
        {
          label: 'Nearest Leak',
          value: (() => {
            if (!acoustic.nearestLeakId) return 'None detected';
            const leakCrack = cracks.find((c) => c.id === acoustic.nearestLeakId);
            return leakCrack
              ? `${leakCrack.id} (${leakCrack.depthM.toFixed(2)} m)`
              : acoustic.nearestLeakId;
          })(),
        },
      ],
    };
  }

  if (partId === 'pressure') {
    const status: PartStatus = rov.depthM >= 0.9 ? 'Alert' : 'Active';
    return {
      id: partId,
      name: 'Pressure / Depth Sensor',
      summary:
        'Measures hydrostatic water pressure and calculates surface-zeroed depth below the 0.00 m datum.',
      status,
      awsService: 'AWS IoT Core → Amazon DynamoDB',
      readings: [
        { label: 'Pressure P (SIM)', value: `${pressureKpa.toFixed(2)} kPa` },
        { label: 'Surface P₀', value: `${ATMOSPHERIC_PRESSURE_KPA.toFixed(2)} kPa` },
        { label: 'Depth (SIM)', value: `${computedDepthM.toFixed(2)} m` },
        { label: 'Formula', value: '(P − P₀) / (997 × 9.81)' },
      ],
    };
  }

  if (partId === 'thrusters') {
    const activeThrust =
      isMoving || pilotVector.vx !== 0 || pilotVector.vy !== 0;
    return {
      id: partId,
      name: '3-Thruster Propulsion Array',
      summary:
        'Drives horizontal wall approach and vertical depth control using one aft surge and two heave thrusters.',
      status: activeThrust ? 'Active' : 'Idle',
      awsService: 'AWS IoT Core (actuator & trim telemetry)',
      readings: [
        {
          label: 'T1 Aft Surge',
          value:
            pilotVector.vx < 0
              ? `${pwm.aftSurgePct}% PWM (REV)`
              : `${pwm.aftSurgePct}% PWM`,
        },
        { label: 'T2 Fore Heave', value: `${pwm.foreHeavePct}% PWM` },
        { label: 'T3 Aft Heave', value: `${pwm.aftHeavePct}% PWM` },
        { label: 'Mode', value: activeThrust ? 'Piloting' : 'Depth Hold Trim' },
      ],
    };
  }

  if (partId === 'tether') {
    const tetherM = Number((0.45 + rov.xM * 0.65 + rov.depthM * 0.95).toFixed(2));
    return {
      id: partId,
      name: 'Umbilical Tether Cable',
      summary:
        'Carries USB video, sensor wires, and thruster power between the ROV and shore unit because no wireless signal works underwater.',
      status: 'Active',
      awsService: 'Shore Bridge → AWS IoT Core & Amazon S3',
      readings: [
        { label: 'Signals Carried', value: 'USB Video · Sensors · Power' },
        { label: 'Wireless Underwater', value: 'None — no wireless underwater' },
        { label: 'Deployed Length (SIM)', value: `${tetherM.toFixed(2)} m` },
      ],
    };
  }

  if (partId === 'shore-unit') {
    const straddledSeverity = straddledCrack
      ? classifySeverity(straddledCrack.trueWidthMm, thresholds)
      : null;
    const hasAlert =
      acoustic.status === 'Active Leak Detected' || straddledSeverity === 'Critical';
    return {
      id: partId,
      name: 'Shore Unit (Laptop + ESP32)',
      summary:
        'Receives wired tether telemetry on the ESP32 and relays frames and MQTT messages from the field laptop to AWS.',
      status: hasAlert ? 'Alert' : 'Active',
      awsService: 'AWS IoT Core (MQTT) & HTTP API Gateway',
      readings: [
        {
          label: 'MQTT Publish (SIM)',
          value: hasAlert ? 'Publishing Alert (1 Hz)' : 'Connected · 1 Hz stream',
        },
        { label: 'MQTT Topic', value: 'sealion/demo-dam/telemetry' },
        { label: 'Latest Depth (SIM)', value: `${rov.depthM.toFixed(2)} m` },
      ],
    };
  }

  // Crack targets: crack-C-01 .. crack-C-04
  const crackId = partId.replace('crack-', '');
  const crack = cracks.find((c) => c.id === crackId) ?? cracks[0];
  const severity = classifySeverity(crack.trueWidthMm, thresholds);
  const status: PartStatus =
    severity === 'Critical' || crack.hasLeak
      ? 'Alert'
      : severity === 'Moderate'
        ? 'Active'
        : 'Idle';

  const readings: PartReadingRow[] = [
    { label: 'Crack Width (SIM)', value: `${crack.trueWidthMm.toFixed(2)} mm` },
    { label: 'Wall Depth (SIM)', value: `${crack.depthM.toFixed(2)} m` },
    { label: 'Active Leak', value: crack.hasLeak ? 'Yes (Acoustic seepage)' : 'No' },
  ];
  if (crack.previousWidthMm !== undefined) {
    const delta = Number((crack.trueWidthMm - crack.previousWidthMm).toFixed(1));
    readings.push({
      label: 'Re-Inspection Delta',
      value: `+${delta.toFixed(1)} mm (${crack.previousWidthMm.toFixed(1)} → ${crack.trueWidthMm.toFixed(1)} mm)`,
    });
  }

  return {
    id: partId,
    name: `Crack ${crack.id} · ${crack.label}`,
    summary: crack.description,
    status,
    severity,
    awsService: 'Amazon DynamoDB (record) & Amazon S3 (frame)',
    readings,
    note: crack.recommendation,
  };
}
